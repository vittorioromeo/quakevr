int genCvarsQc(const Ctx& ctx, const Args& args, Out& out)
{
    // {name: first file using it}
    Map<za::String, za::String> used;
    za::Vector<za::String> paths;
    for(const auto& p : listFiles(ctx.tree / "QC", {".qc"}, true))
    {
        // (sorted as Python's glob paths: "QC\\sub\\x.qc")
        za::String s = "QC\\" + pathStr(p.lexically_relative(ctx.tree / "QC"));
        replaceChar(s, '/', '\\');
        paths.pushBack(ZA_MOVE(s));
    }
    sortStrings(paths);
    for(auto& path : paths)
    {
        replaceChar(path, '\\', '/');
        if(path == outPath)
        {
            continue;
        }
        const za::String text = stripComments(readText(ctx.tree / toPath(path)));
        for(za::SizeT i = 0; (i = text.find("cvarh_", i)) != npos;)
        {
            const za::SizeT a = i + 6;
            if(!wordStart(text, i))
            {
                i = a;
                continue;
            }
            za::SizeT e = a;
            while(e < text.size() && isWord(text[e]))
            {
                ++e;
            }
            if(e > a)
            {
                used.try_emplace(za::String{text.substrByPosLen(a, e - a)}, path);
            }
            i = e;
        }
    }
    const auto known = knownNames(ctx);
    const auto usedSorted = qza::sortedByKey(used);
    za::String text = "// Generated by qvr_checks cvars_qc (Tools/qvr_checks) from the QC's cvarh_ uses: do not edit (run "
                      "it after adding or\n// removing a cvarh_<name> use). Every cvar and tuning constant the QC reads "
                      "by handle (cvar_hget).\n\n";
    for(const auto* e : usedSorted)
    {
        appendFmt(text, "float cvarh_{};\n", e->first);
    }
    text += "\nvoid() VR_CVars_InitGenerated =\n{\n";
    for(const auto* e : usedSorted)
    {
        appendFmt(text, "    cvarh_{} = VR_CVar_Make(\"{}\");\n", e->first, e->first);
    }
    text += "}\n";
    za::SizeT unknown = 0;
    for(const auto* e : usedSorted)
    {
        if(!known.contains(e->first))
        {
            ++unknown;
            out.line("{}: cvarh_{} names no cvar or tuning constant (misspelt or retired?)", e->second, e->first);
        }
    }
    bool had = false;
    const za::String old = readRaw(ctx.tree / outPath, &had);
    const bool same = had && old == text;
    if(has(args, "--check"))
    {
        if(!same)
        {
            out.line("{} is stale: run build/qvr_checks/qvr_checks.exe cvars_qc and commit it", outPath);
            return 1;
        }
        return unknown ? 1 : 0;
    }
    if(!same && !writeRaw(ctx.tree / outPath, text))
    {
        out.line("{}: cannot write it", outPath);
        return 1;
    }
    out.line("{}: {} handles, {} unknown", outPath, used.size(), unknown);
    return unknown ? 1 : 0;
}

