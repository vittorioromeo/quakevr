int genCvarsQc(const Ctx& ctx, const Args& args, Out& out)
{
    // {name: first file using it}
    std::map<std::string, std::string> used;
    std::vector<std::string> paths;
    for(const auto& p : listFiles(ctx.tree / "QC", {".qc"}, true))
    {
        // (sorted as Python's glob paths: "QC\\sub\\x.qc")
        std::string s = "QC\\" + p.lexically_relative(ctx.tree / "QC").string();
        std::replace(s.begin(), s.end(), '/', '\\');
        paths.push_back(std::move(s));
    }
    sortStrings(paths);
    for(auto& path : paths)
    {
        std::replace(path.begin(), path.end(), '\\', '/');
        if(path == outPath)
        {
            continue;
        }
        const std::string text = stripComments(readText(ctx.tree / path));
        for(size_t i = 0; (i = text.find("cvarh_", i)) != std::string::npos;)
        {
            const size_t a = i + 6;
            if(!wordStart(text, i))
            {
                i = a;
                continue;
            }
            size_t e = a;
            while(e < text.size() && isWord(text[e]))
            {
                ++e;
            }
            if(e > a)
            {
                used.emplace(text.substr(a, e - a), path);
            }
            i = e;
        }
    }
    const auto known = knownNames(ctx);
    std::string text = "// Generated by qvr_checks cvars_qc (Tools/qvr_checks) from the QC's cvarh_ uses: do not edit (run "
                       "it after adding or\n// removing a cvarh_<name> use). Every cvar and tuning constant the QC reads "
                       "by handle (cvar_hget).\n\n";
    for(const auto& [n, _] : used)
    {
        text += std::format("float cvarh_{};\n", n);
    }
    text += "\nvoid() VR_CVars_InitGenerated =\n{\n";
    for(const auto& [n, _] : used)
    {
        text += std::format("    cvarh_{} = VR_CVar_Make(\"{}\");\n", n, n);
    }
    text += "}\n";
    size_t unknown = 0;
    for(const auto& [n, path] : used)
    {
        if(!known.contains(n))
        {
            ++unknown;
            out.line("{}: cvarh_{} names no cvar or tuning constant (misspelt or retired?)", path, n);
        }
    }
    bool had = false;
    const std::string old = readRaw(ctx.tree / outPath, &had);
    const bool same = had && old == text;
    if(std::find(args.begin(), args.end(), "--check") != args.end())
    {
        if(!same)
        {
            out.line("{} is stale: run build/qvr_checks/qvr_checks.exe cvars_qc and commit it", outPath);
            return 1;
        }
        return unknown ? 1 : 0;
    }
    if(!same && !writeRaw(ctx.tree / outPath, text))
    {
        out.line("{}: cannot write it", outPath);
        return 1;
    }
    out.line("{}: {} handles, {} unknown", outPath, used.size(), unknown);
    return unknown ? 1 : 0;
}

