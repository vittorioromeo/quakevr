constexpr const char* outPath = "QC/vr_cvars_gen.qc";

// Comments become one space; string literals stay (a `"..."` on one line, escapes included).
za::String stripComments(za::StringView t)
{
    za::String o;
    o.reserve(t.size());
    za::SizeT i = 0;
    while(i < t.size())
    {
        const char c = t[i];
        if(c == '"')
        {
            za::SizeT j = i + 1;
            bool closed = false;
            while(j < t.size() && t[j] != '\n')
            {
                if(t[j] == '\\' && j + 1 < t.size())
                {
                    j += 2;
                    continue;
                }
                if(t[j] == '"')
                {
                    closed = true;
                    break;
                }
                ++j;
            }
            if(closed)
            {
                o.append(t.substrByPosLen(i, j + 1 - i));
                i = j + 1;
                continue;
            }
            o += c;
            ++i;
        }
        else if(c == '/' && i + 1 < t.size() && t[i + 1] == '/')
        {
            while(i < t.size() && t[i] != '\n')
            {
                ++i;
            }
            o += ' ';
        }
        else if(c == '/' && i + 1 < t.size() && t[i + 1] == '*')
        {
            const za::SizeT e = t.find("*/", i + 2);
            if(e == npos)
            {
                o += c;
                ++i;
                continue;
            }
            o += ' ';
            i = e + 2;
        }
        else
        {
            o += c;
            ++i;
        }
    }
    return o;
}

// A regex match's group as text.
za::StringView group(const std::cmatch& m, int g)
{
    return za::StringView(m[g].first, static_cast<za::SizeT>(m[g].length()));
}

// Every `^\s*MACRO(name,` (re.M) in a file; `indented` false: `^MACRO(name,`.
void macroNames(const fs::path& path, za::StringView macro, Set<za::String>& names, bool indented = true)
{
    za::String pattern = indented ? "\\s*" : "";
    pattern += macro;
    pattern += "\\((\\w+),";
    for(auto& n : lineStartGroups(readText(path), pattern, macro[0]))
    {
        names.insert(ZA_MOVE(n));
    }
}

Set<za::String> knownNames(const Ctx& ctx)
{
    Set<za::String> names;
    const fs::path vr = ctx.tree / "Quake/vr";
    macroNames(vr / "vr_cvars.inc", "QVR_CVAR", names);
    macroNames(vr / "vr_tunables.inc", "QVR_TUNABLE", names);
    macroNames(vr / "vr_monsterdata.inc", "QVR_MONSTER_VALUE", names);
    macroNames(vr / "vr_weaponvalues.inc", "QVR_WEAPON_VALUE", names);
    // The monster groups' values by their old cvar names (Misc/quakevr/groups_data.py old_name; the keys:
    // vr_mgroups.cpp paramKeys, the groups: vr_mgroups.inc QVR_MGROUP).
    Set<za::String> groupSet;
    macroNames(vr / "vr_mgroups.inc", "QVR_MGROUP", groupSet, false);
    za::Vector<za::String> keys;
    {
        const za::String src = readText(vr / "vr_mgroups.cpp");
        std::cmatch m;
        if(std::regex_search(src.begin(), src.end(), m, std::regex(R"(paramKeys\[[^\]]*\]\s*=\s*\{([^}]*)\})")))
        {
            const za::String list{group(m, 1)};
            const std::regex key("\"(\\w+)\"");
            for(std::cregex_iterator it(list.begin(), list.end(), key), end; it != end; ++it)
            {
                keys.emplaceBack(group(*it, 1));
            }
        }
    }
    for(const auto& g : groupSet)
    {
        for(const auto& k : keys)
        {
            names.insert(k == "resist"  ? "vr_kdtrig_resist_" + g
                         : k == "shove" ? "vr_knockdown_chance_" + g
                                        : "vr_mgrp_" + g + "_" + k);
        }
    }
    // the weapon slots' settings, vr_wofs_<key>_<slot> (vr_weapons.cpp: a cvar per slot and key of vr_weapons.inc)
    const za::Vector<za::String> wkeys =
        lineStartGroups(readText(vr / "vr_weapons.inc"), R"re(\s*QVR_WEAPON_KEY\(\w+,\s*"(\w+)")re", 'Q');
    int slots = 0;
    {
        const za::String text = readText(vr / "vr_cvars.hpp");
        std::cmatch m;
        if(std::regex_search(text.begin(), text.end(), m, std::regex(R"(weaponSlotCount\s*=\s*(\d+))")))
        {
            slots = static_cast<int>(toInt(group(m, 1)));
        }
    }
    for(const auto& k : wkeys)
    {
        for(int i = 0; i <= slots; ++i) // (numbered from 0 or 1: both)
        {
            names.insert(fmt("vr_wofs_{}_{:02}", k, i));
        }
    }
    // \bcvar_t\s+\w+\s*=\s*\{\s*"(\w+)"  (tried where "cvar_t" starts a word)
    const std::regex cvarT(R"re(cvar_t\s+\w+\s*=\s*\{\s*"(\w+)")re");
    for(const auto& path : listFiles(ctx.tree / "Quake", {".c", ".cpp", ".h", ".hpp", ".inc"}, true))
    {
        if(relPosix(path, ctx.tree).find("external") != npos)
        {
            continue;
        }
        const za::String text = readText(path);
        for(za::SizeT i = 0; (i = text.find("cvar_t", i)) != npos; i += 6)
        {
            if(!wordStart(text, i))
            {
                continue;
            }
            std::cmatch m;
            if(std::regex_search(text.begin() + i, text.end(), m, cvarT, std::regex_constants::match_continuous))
            {
                names.emplace(group(m, 1));
            }
        }
    }
    return names;
}

