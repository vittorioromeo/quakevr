// cvars_qc: QC/vr_cvars_gen.qc, every cvar handle the QC reads, made from its uses.
//
// The QC reads a cvar or a tuning constant by handle: `cvar_hget(cvarh_<name>)` (an index read; `cvar("<name>")` looks
// the name up each call, through the cvars then the tunables). Writing `cvarh_<name>` anywhere in the QC is the whole
// declaration: this finds every `cvarh_<name>` the QC's code uses (comments aside), and writes, for each, its global
// and the line that makes it (VR_CVars_InitGenerated, called from VR_CVars_InitAllHandles when a map loads). So a
// handle cannot be declared without being made, and none is left over when its last use goes (a handle costs a QC
// global).
//
// Each name must be a cvar or a tuning constant the engine has: Quake VR's (Quake/vr/vr_cvars.inc QVR_CVAR, the
// tunables, the per-weapon and per-monster values, the monster groups' values by their old cvar names), or the
// engine's own (a `cvar_t x = {"name", ...}` in Quake/). A name that is none of these fails (in both modes): a
// misspelt or retired cvar. The game checks again when it makes the handles (VR_CVar_Make: a "cvar_hmake: unknown
// cvar" line, and every QC test then fails).
//
//   qvr_checks cvars_qc           write QC/vr_cvars_gen.qc (when it changed)
//   qvr_checks cvars_qc --check   exit 1 when it is not what this would write, or a name is unknown
//
// After adding or removing a `cvarh_` use: run it, and commit the generated file. QC/ad (the Arcane Dimensions import,
// generated by ad_import.py) keeps its cvar("...").
#include "common.hpp"

