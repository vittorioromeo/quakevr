constexpr const char* outPath = "QC/vr_cvars_gen.qc";

// Comments become one space; string literals stay (a `"..."` on one line, escapes included).
std::string stripComments(std::string_view t)
{
    std::string o;
    o.reserve(t.size());
    size_t i = 0;
    while(i < t.size())
    {
        const char c = t[i];
        if(c == '"')
        {
            size_t j = i + 1;
            bool closed = false;
            while(j < t.size() && t[j] != '\n')
            {
                if(t[j] == '\\' && j + 1 < t.size())
                {
                    j += 2;
                    continue;
                }
                if(t[j] == '"')
                {
                    closed = true;
                    break;
                }
                ++j;
            }
            if(closed)
            {
                o.append(t.substr(i, j + 1 - i));
                i = j + 1;
                continue;
            }
            o += c;
            ++i;
        }
        else if(c == '/' && i + 1 < t.size() && t[i + 1] == '/')
        {
            while(i < t.size() && t[i] != '\n')
            {
                ++i;
            }
            o += ' ';
        }
        else if(c == '/' && i + 1 < t.size() && t[i + 1] == '*')
        {
            const size_t e = t.find("*/", i + 2);
            if(e == std::string_view::npos)
            {
                o += c;
                ++i;
                continue;
            }
            o += ' ';
            i = e + 2;
        }
        else
        {
            o += c;
            ++i;
        }
    }
    return o;
}

// Every `^\s*MACRO(name,` (re.M) in a file; `indented` false: `^MACRO(name,`.
void macroNames(const fs::path& path, const std::string& macro, std::set<std::string>& names, bool indented = true)
{
    for(auto& n : lineStartGroups(readText(path), (indented ? "\\s*" : "") + macro + "\\((\\w+),", macro[0]))
    {
        names.insert(std::move(n));
    }
}

std::set<std::string> knownNames(const Ctx& ctx)
{
    std::set<std::string> names;
    const fs::path vr = ctx.tree / "Quake/vr";
    macroNames(vr / "vr_cvars.inc", "QVR_CVAR", names);
    macroNames(vr / "vr_tunables.inc", "QVR_TUNABLE", names);
    macroNames(vr / "vr_monsterdata.inc", "QVR_MONSTER_VALUE", names);
    macroNames(vr / "vr_weaponvalues.inc", "QVR_WEAPON_VALUE", names);
    // The monster groups' values by their old cvar names (Misc/quakevr/groups_data.py old_name; the keys:
    // vr_mgroups.cpp paramKeys, the groups: vr_mgroups.inc QVR_MGROUP).
    std::set<std::string> groupSet;
    macroNames(vr / "vr_mgroups.inc", "QVR_MGROUP", groupSet, false);
    std::vector<std::string> keys;
    {
        const std::string src = readText(vr / "vr_mgroups.cpp");
        std::smatch m;
        if(std::regex_search(src, m, std::regex(R"(paramKeys\[[^\]]*\]\s*=\s*\{([^}]*)\})")))
        {
            const std::string list = m[1].str();
            const std::regex key("\"(\\w+)\"");
            for(std::sregex_iterator it(list.begin(), list.end(), key), end; it != end; ++it)
            {
                keys.push_back((*it)[1].str());
            }
        }
    }
    for(const auto& g : groupSet)
    {
        for(const auto& k : keys)
        {
            names.insert(k == "resist"  ? "vr_kdtrig_resist_" + g
                         : k == "shove" ? "vr_knockdown_chance_" + g
                                        : "vr_mgrp_" + g + "_" + k);
        }
    }
    // the weapon slots' settings, vr_wofs_<key>_<slot> (vr_weapons.cpp: a cvar per slot and key of vr_weapons.inc)
    std::vector<std::string> wkeys;
    {
        wkeys = lineStartGroups(readText(vr / "vr_weapons.inc"), R"re(\s*QVR_WEAPON_KEY\(\w+,\s*"(\w+)")re", 'Q');
    }
    int slots = 0;
    {
        const std::string text = readText(vr / "vr_cvars.hpp");
        std::smatch m;
        if(std::regex_search(text, m, std::regex(R"(weaponSlotCount\s*=\s*(\d+))")))
        {
            slots = std::stoi(m[1].str());
        }
    }
    for(const auto& k : wkeys)
    {
        for(int i = 0; i <= slots; ++i) // (numbered from 0 or 1: both)
        {
            names.insert(std::format("vr_wofs_{}_{:02}", k, i));
        }
    }
    // \bcvar_t\s+\w+\s*=\s*\{\s*"(\w+)"  (tried where "cvar_t" starts a word)
    const std::regex cvarT(R"re(cvar_t\s+\w+\s*=\s*\{\s*"(\w+)")re");
    for(const auto& path : listFiles(ctx.tree / "Quake", {".c", ".cpp", ".h", ".hpp", ".inc"}, true))
    {
        if(relPosix(path, ctx.tree).find("external") != std::string::npos)
        {
            continue;
        }
        const std::string text = readText(path);
        for(size_t i = 0; (i = text.find("cvar_t", i)) != std::string::npos; i += 6)
        {
            if(!wordStart(text, i))
            {
                continue;
            }
            std::smatch m;
            if(std::regex_search(text.begin() + static_cast<std::ptrdiff_t>(i), text.end(), m, cvarT,
                                 std::regex_constants::match_continuous))
            {
                names.insert(m[1].str());
            }
        }
    }
    return names;
}

