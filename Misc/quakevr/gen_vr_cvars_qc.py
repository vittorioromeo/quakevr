#!/usr/bin/env python3
"""gen_vr_cvars_qc.py -- QC/vr_cvars_gen.qc: the QC's cvar handles for Quake VR's own cvars.

A handle (`cvarh_<name>`, read with cvar_hget) is made for every cvar of Quake/vr/vr_cvars.inc (a literal
`QVR_CVAR(<name>, ...)` line) whose handle the QC uses, and for no other: a handle costs a QC global, and the globals
are near the progs format's limit. The handles of the engine's own cvars (deathmatch, skill, sv_gravity, ...) and of
cvars vr_cvars.inc makes through its macros stay hand-written in QC/vr_cvars.qc, which includes the generated file and
calls VR_CVars_InitGenerated() from VR_CVars_InitAllHandles.

  python Misc/quakevr/gen_vr_cvars_qc.py           write QC/vr_cvars_gen.qc (when it changed)
  python Misc/quakevr/gen_vr_cvars_qc.py --check   exit 1 when QC/vr_cvars_gen.qc is not what this would write

Run from the repository's root (the kit's build.sh runs --check). A new `cvarh_<name>` in the QC for a vr_cvars.inc
cvar: run this, and commit the generated file.
"""
import glob
import re
import sys

INC = "Quake/vr/vr_cvars.inc"
HAND = "QC/vr_cvars.qc"
OUT = "QC/vr_cvars_gen.qc"


def used_handles():
    used = set()
    for path in glob.glob("QC/**/*.qc", recursive=True):
        path = path.replace("\\", "/")
        if path == OUT:
            continue
        text = open(path, encoding="utf-8", errors="replace").read()
        if path == HAND:
            # its own declarations and makes are not uses
            text = re.sub(r"^float cvarh_\w+;.*$", "", text, flags=re.M)
            text = re.sub(r"VR_CVAR_HMAKE\(\w+\)", "", text)
        used |= set(re.findall(r"\bcvarh_(\w+)", text))
    return used


def hand_handles():
    return set(re.findall(r"^float cvarh_(\w+);", open(HAND, encoding="utf-8").read(), re.M))


def generate():
    inc = re.findall(r"^QVR_CVAR\((\w+),", open(INC, encoding="utf-8").read(), re.M)
    used = used_handles()
    hand = hand_handles()
    names = []
    seen = set()
    for n in inc:
        if n in used and n not in hand and n not in seen:
            names.append(n)
            seen.add(n)
    out = ["// Generated by Misc/quakevr/gen_vr_cvars_qc.py from Quake/vr/vr_cvars.inc and the QC's uses: do not edit.",
           "// The handles of Quake VR's own cvars the QC reads (cvar_hget); the engine's and the macro-made ones are",
           "// hand-written in vr_cvars.qc, which includes this file.", ""]
    out += ["float cvarh_%s;" % n for n in names]
    out += ["", "void() VR_CVars_InitGenerated =", "{"]
    out += ["    cvarh_%s = cvar_hmake(\"%s\");" % (n, n) for n in names]
    out += ["}", ""]
    return "\n".join(out), len(names)


def main():
    text, n = generate()
    try:
        old = open(OUT, encoding="utf-8", newline="").read()
    except FileNotFoundError:
        old = None
    if "--check" in sys.argv:
        if old != text:
            print("%s is stale: run python Misc/quakevr/gen_vr_cvars_qc.py and commit it" % OUT)
            return 1
        return 0
    if old != text:
        open(OUT, "w", encoding="utf-8", newline="").write(text)
    print("%s: %d handles" % (OUT, n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
