#!/usr/bin/env python3
"""gen_vr_cvars_qc.py -- QC/vr_cvars_gen.qc: every cvar handle the QC reads, made from its uses.

The QC reads a cvar or a tuning constant by handle: `cvar_hget(cvarh_<name>)` (an index read; `cvar("<name>")` looks
the name up each call, through the cvars then the tunables). Writing `cvarh_<name>` anywhere in the QC is the whole
declaration: this script finds every `cvarh_<name>` the QC's code uses (comments aside), and writes, for each, its
global and the line that makes it (VR_CVars_InitGenerated, called from VR_CVars_InitAllHandles when a map loads). So a
handle cannot be declared without being made, and none is left over when its last use goes (a handle costs a QC
global, and the globals are near the progs format's limit: 65,536).

Each name must be a cvar or a tuning constant the engine has: Quake VR's (Quake/vr/vr_cvars.inc QVR_CVAR, the
tunables, the per-weapon and per-monster values, the monster groups' values by their old cvar names), or the engine's
own (a `cvar_t x = {"name", ...}` in Quake/). A name that is none of these fails (in both modes): a misspelt or retired
cvar. The game checks again when it makes the handles (VR_CVar_Make: a "cvar_hmake: unknown cvar" line, and every QC
test then fails).

  python Misc/quakevr/gen_vr_cvars_qc.py           write QC/vr_cvars_gen.qc (when it changed)
  python Misc/quakevr/gen_vr_cvars_qc.py --check   exit 1 when it is not what this would write, or a name is unknown

Run from the repository's root (the kit's build.sh runs --check). After adding or removing a `cvarh_` use: run this,
and commit the generated file. QC/ad (the Arcane Dimensions import, generated by ad_import.py) keeps its cvar("...").
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import groups_data  # noqa: E402  (the monster groups' values' old cvar names)

INC = "Quake/vr/vr_cvars.inc"
TUNABLES = "Quake/vr/vr_tunables.inc"
MONSTERS = "Quake/vr/vr_monsterdata.inc"
WEAPON_VALUES = "Quake/vr/vr_weaponvalues.inc"
WEAPON_KEYS = "Quake/vr/vr_weapons.inc"
SLOTS = "Quake/vr/vr_cvars.hpp"
OUT = "QC/vr_cvars_gen.qc"

_TOKENS = re.compile(r'"(?:\\.|[^"\\\n])*"|//[^\n]*|/\*.*?\*/', re.S)


def strip_comments(text):
    return _TOKENS.sub(lambda m: m.group(0) if m.group(0)[0] == '"' else " ", text)


def used_handles():
    """{name: first file using it}"""
    used = {}
    for path in sorted(glob.glob("QC/**/*.qc", recursive=True)):
        path = path.replace("\\", "/")
        if path == OUT:
            continue
        text = strip_comments(open(path, encoding="latin-1").read())
        for n in re.findall(r"\bcvarh_(\w+)", text):
            used.setdefault(n, path)
    return used


def known_names():
    """Every cvar and tuning constant name the engine has (cvar_hmake finds)."""
    names = set()
    for path, macro in ((INC, "QVR_CVAR"), (TUNABLES, "QVR_TUNABLE"), (MONSTERS, "QVR_MONSTER_VALUE"),
                        (WEAPON_VALUES, "QVR_WEAPON_VALUE")):
        names |= set(re.findall(r"^\s*%s\((\w+)," % macro, open(path, encoding="utf-8").read(), re.M))
    for g in groups_data.read_groups():
        for k in groups_data.KEYS:
            names.add(groups_data.old_name(g, k))
    # the weapon slots' settings, vr_wofs_<key>_<slot> (vr_weapons.cpp: a cvar per slot and key of vr_weapons.inc)
    keys = re.findall(r"^\s*QVR_WEAPON_KEY\(\w+,\s*\"(\w+)\"", open(WEAPON_KEYS, encoding="utf-8").read(), re.M)
    slots = int(re.search(r"weaponSlotCount\s*=\s*(\d+)", open(SLOTS, encoding="utf-8").read()).group(1))
    names |= {"vr_wofs_%s_%02d" % (k, i) for k in keys for i in range(slots + 1)}  # (numbered from 0 or 1: both)
    for ext in ("c", "cpp", "h", "hpp", "inc"):
        for path in glob.glob("Quake/**/*." + ext, recursive=True):
            if "external" in path.replace("\\", "/"):
                continue
            text = open(path, encoding="latin-1").read()
            names |= set(re.findall(r"\bcvar_t\s+\w+\s*=\s*\{\s*\"(\w+)\"", text))
    return names


def generate():
    used = used_handles()
    known = known_names()
    unknown = sorted(n for n in used if n not in known)
    names = sorted(used)
    out = ["// Generated by Misc/quakevr/gen_vr_cvars_qc.py from the QC's cvarh_ uses: do not edit (run it after adding or",
           "// removing a cvarh_<name> use). Every cvar and tuning constant the QC reads by handle (cvar_hget).", ""]
    out += ["float cvarh_%s;" % n for n in names]
    out += ["", "void() VR_CVars_InitGenerated =", "{"]
    out += ["    cvarh_%s = VR_CVar_Make(\"%s\");" % (n, n) for n in names]
    out += ["}", ""]
    return "\n".join(out), len(names), [(n, used[n]) for n in unknown]


def main():
    text, n, unknown = generate()
    for name, path in unknown:
        print("%s: cvarh_%s names no cvar or tuning constant (misspelt or retired?)" % (path, name))
    try:
        old = open(OUT, encoding="utf-8", newline="").read()
    except FileNotFoundError:
        old = None
    if "--check" in sys.argv:
        if old != text:
            print("%s is stale: run python Misc/quakevr/gen_vr_cvars_qc.py and commit it" % OUT)
            return 1
        return 1 if unknown else 0
    if old != text:
        open(OUT, "w", encoding="utf-8", newline="").write(text)
    print("%s: %d handles, %d unknown" % (OUT, n, len(unknown)))
    return 1 if unknown else 0


if __name__ == "__main__":
    sys.exit(main())
