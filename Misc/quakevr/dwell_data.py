#!/usr/bin/env python3
"""dwell_data.py -- writes Quake/vr/vr_dwell_data.inc (vr_dwell.cpp) from a Dwell v2.2 folder and the official paks.

  python -I Misc/quakevr/dwell_data.py <dwell folder> <Quake folder with id1 (hipnotic, rogue)>

The release's pin (progs.dat's size and SHA-256: v2.2's) and Dwell's files an official pak also has (names only, no
content): the engine skips those in Dwell's folder, so Dwell supplies only its own files and our VR models, heads and
sounds stay Quake's (DWELL.md 3; AD's vr_ad_data.inc is the same list for AD, written by ad_import.py --engine-lists).
maps/start.bsp is Dwell's own (the campaign's start), never skipped. Dwell's files are read as data, never run.
"""

import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qc_import  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "Quake", "vr", "vr_dwell_data.inc")


def dwell_names(folder):
    names = set()
    for dirpath, _dirs, files in os.walk(folder):
        for fn in files:
            rel = os.path.relpath(os.path.join(dirpath, fn), folder).replace("\\", "/").lower()
            if re.match(r"pak\d+\.pak$", rel):
                names |= {n.lower() for n in qc_import.read_pak(os.path.join(dirpath, fn))}
            else:
                names.add(rel)
    return names


def official_owners(quake):
    owner = {}
    for game, tag in (("id1", 0), ("hipnotic", 1), ("rogue", 2)):
        folder = os.path.join(quake, game)
        paks = sorted(fn for fn in os.listdir(folder) if re.match(r"pak\d+\.pak$", fn, re.I)) if os.path.isdir(folder) else []
        if game == "id1" and not paks:
            sys.exit("dwell_data: no id1 paks in %s" % quake)
        for fn in paks:
            for n in qc_import.read_pak(os.path.join(folder, fn)):
                owner.setdefault(n.lower(), tag)
    return owner


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    dwell, quake = sys.argv[1], sys.argv[2]
    with open(os.path.join(dwell, "progs.dat"), "rb") as f:
        progs = f.read()
    owner = official_owners(quake)
    shadowed = sorted(n for n in dwell_names(dwell) if n in owner and n != "maps/start.bsp")
    lines = ["// Generated by Misc/quakevr/dwell_data.py from Dwell v2.2 and the official paks' file names (no content); never",
             "// edit. vr_dwell.cpp: the release pin (progs.dat) and Dwell's files an official pak has too (skipped in Dwell's",
             "// folder; the second argument is the official owner: 0 id1, 1 hipnotic, 2 rogue).",
             "#define VR_DWELL_PROGS_SIZE %d" % len(progs),
             "#define VR_DWELL_PROGS_SHA \"%s\"" % hashlib.sha256(progs).hexdigest()]
    lines += ["VR_DWELL_SHADOWED(\"%s\", %d)" % (n, owner[n]) for n in shadowed]
    with open(OUT, "w", encoding="latin1", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("dwell_data: %s: %d shadowed files (id1 %d, hipnotic %d, rogue %d); progs.dat %d bytes" % (
        os.path.relpath(OUT, ROOT), len(shadowed), sum(owner[n] == 0 for n in shadowed),
        sum(owner[n] == 1 for n in shadowed), sum(owner[n] == 2 for n in shadowed), len(progs)))


if __name__ == "__main__":
    main()
