#!/usr/bin/env python3
"""dwell_data.py -- writes Quake/vr/vr_dwell_data.inc (vr_dwell.cpp) from a Dwell v2.2 folder and the official paks.

  python -I Misc/quakevr/dwell_data.py <dwell folder> <Quake folder with id1, ad (hipnotic, rogue)>

The release's pin (progs.dat's size and SHA-256: v2.2's) and Dwell's files an official pak or Arcane Dimensions also
has (names only, no content): the engine skips those in Dwell's folder, so Dwell supplies only its own files and our VR
models, heads and sounds stay Quake's, AD's models AD's (Dwell's mon_knight, mon_enforcer... are other meshes than the
ones AD's rigs and frames are made for; the same rule as quoth_data.py's), except KEEP (DWELL.md 3; AD's
vr_ad_data.inc is the same list for AD, written by ad_import.py --engine-lists).
maps/start.bsp is Dwell's own (the campaign's start), never skipped. Dwell's files are read as data, never run.
"""

import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qc_import  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "Quake", "vr", "vr_dwell_data.inc")


def dwell_names(folder):
    names = set()
    for dirpath, _dirs, files in os.walk(folder):
        for fn in files:
            rel = os.path.relpath(os.path.join(dirpath, fn), folder).replace("\\", "/").lower()
            if re.match(r"pak\d+\.pak$", rel):
                names |= {n.lower() for n in qc_import.read_pak(os.path.join(dirpath, fn))}
            else:
                names.add(rel)
    return names


def official_owners(quake):
    owner = {}
    for game, tag in (("id1", 0), ("hipnotic", 1), ("rogue", 2), ("ad", 3)):
        folder = os.path.join(quake, game)
        paks = sorted(fn for fn in os.listdir(folder) if re.match(r"pak\d+\.pak$", fn, re.I)) if os.path.isdir(folder) else []
        if game in ("id1", "ad") and not paks:
            sys.exit("dwell_data: no %s paks in %s" % (game, quake))
        for fn in paks:
            for n in qc_import.read_pak(os.path.join(folder, fn)):
                owner.setdefault(n.lower(), tag)
    return owner


# AD's names Dwell keeps: its models only are AD's (its maps' skies, menus, lit files stay its own), and of
# those what our Dwell entities draw from Dwell's own copy (QC/dwell/dw_items.qc: the Rotary
# Shotgun's pickup is Dwell's g_shot3.mdl, AD's is another gun).
KEEP = {"progs/g_shot3.mdl"}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    dwell, quake = sys.argv[1], sys.argv[2]
    with open(os.path.join(dwell, "progs.dat"), "rb") as f:
        progs = f.read()
    owner = official_owners(quake)
    shadowed = sorted(n for n in dwell_names(dwell) if n in owner and n != "maps/start.bsp" and
                      not (owner[n] == 3 and (n in KEEP or not n.startswith("progs/"))))
    lines = ["// Generated by Misc/quakevr/dwell_data.py from Dwell v2.2 and the official paks' and AD's file names (no",
             "// content); never edit. vr_dwell.cpp: the release pin (progs.dat) and Dwell's files an official pak or AD has too",
             "// (skipped in Dwell's folder, AD's while AD is installed; the second argument is the owner: 0 id1, 1 hipnotic,",
             "// 2 rogue, 3 ad).",
             "#define VR_DWELL_PROGS_SIZE %d" % len(progs),
             "#define VR_DWELL_PROGS_SHA \"%s\"" % hashlib.sha256(progs).hexdigest()]
    lines += ["VR_DWELL_SHADOWED(\"%s\", %d)" % (n, owner[n]) for n in shadowed]
    with open(OUT, "w", encoding="latin1", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("dwell_data: %s: %d shadowed files (id1 %d, hipnotic %d, rogue %d, ad %d); progs.dat %d bytes" % (
        os.path.relpath(OUT, ROOT), len(shadowed), *(sum(owner[n] == t for n in shadowed) for t in range(4)), len(progs)))


if __name__ == "__main__":
    main()
