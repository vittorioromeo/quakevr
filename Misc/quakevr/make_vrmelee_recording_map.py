"""The dedicated melee recording room: python make_vrmelee_recording_map.py --compile."""
import argparse
import os
import shutil
import subprocess
import sys

from maps.mapgeom import MapWriter, box

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
NAME = "vrmelee-recording"
OUT = os.path.join(ROOT, "quakevr", "maps", NAME + ".map")
TOOLS = "C:/OHWorkspace/ericw-tools-2.0.0-alpha11-win64"
# All distinct melee weapons, including both knights' swords. Fists need no pickup.
WEAPONS = [(2, 0), (3, 0), (13, 0), (13, 1), (14, 0), (17, 0), (18, 0)]


def write():
    m = MapWriter()
    # Clear 1280 x 1280 x 384 unit room (39 x 39 x 11.7 m at the default scale).
    # The only collision in the practice area is the central dummy.
    for bounds, texture in [
        ((-656, -656, -16, 656, 656, 0), "qvr_floor"),
        ((-656, -656, 384, 656, 656, 400), "qvr_ceiling"),
        ((-656, -656, 0, -640, 656, 384), "qvr_wall"),
        ((640, -656, 0, 656, 656, 384), "qvr_wall"),
        ((-640, -656, 0, 640, -640, 384), "qvr_wall"),
        ((-640, 640, 0, 640, 656, 384), "qvr_wall"),
    ]:
        m.world.append(box(*bounds, texture))
    m.add({"classname": "info_player_start", "origin": "0 -128 24", "angle": "90"})
    m.add({"classname": "vr_dummy", "origin": "0 0 24", "angle": "270"})
    # Along the south wall, out of the recording area; no racks, tables or other props.
    for i, (weapon, flags) in enumerate(WEAPONS):
        m.add({"classname": "func_weapon_grabbable", "origin": f"{-384 + 128 * i} -512 24",
               "weapon": str(weapon), "weaponflags": str(flags), "spawnflags": "3", "angles": "0 0 0"})
    for x in (-384, 0, 384):
        for y in (-384, 0, 384):
            m.add({"classname": "light", "origin": f"{x} {y} 344", "light": "180", "wait": "0.6",
                   "_color": "1 0.97 0.92"})
    m.write(OUT, {"classname": "worldspawn", "mapversion": "220", "wad": "quakevr/wads/quakevr_dev.wad",
                  "message": "Melee Recording", "worldtype": "2", "_minlight": "255", "_vr_debris": "0",
                  "_vr_crates": "0", "_qvr_prelit": "1"},
            "// Game: Quake VR\n// Format: Valve\n// Generated by Misc/quakevr/make_vrmelee_recording_map.py\n")
    print(f"{NAME}: {len(m.world)} brushes, 1 central dummy, {len(WEAPONS)} melee weapons, 1280 x 1280 clear floor")


def compile_map(tools, work):
    os.makedirs(work, exist_ok=True)
    src, bsp = (os.path.join(work, NAME + ext) for ext in (".map", ".bsp"))
    shutil.copyfile(OUT, src)
    for cmd in ([os.path.join(tools, "qbsp.exe"), "-nolog", "-nopercent", "-wadpath", ROOT, src, bsp],
                [os.path.join(tools, "vis.exe"), "-nolog", "-nopercent", bsp],
                [os.path.join(tools, "light.exe"), "-nolog", "-nopercent", "-extra4", "-dirt", "-dirtscale", "1.5",
                 "-dirtdepth", "96", "-bounce", "-lit", "-lux", "-lightgrid", "-lightgrid_dist", "64", "64", "64", bsp]):
        result = subprocess.run(cmd, capture_output=True, text=True)
        with open(os.path.join(work, os.path.basename(cmd[0]) + ".log"), "w") as log:
            log.write(result.stdout + result.stderr)
        warnings = [l for l in (result.stdout + result.stderr).splitlines() if "WARNING" in l.upper() or "ERROR" in l.upper()]
        print(f"{os.path.basename(cmd[0])}: exit {result.returncode}" + "".join("\n  " + w for w in warnings[:12]))
        if result.returncode:
            sys.exit(1)
    for ext in (".bsp", ".lit", ".lux"):
        shutil.copyfile(os.path.join(work, NAME + ext), os.path.join(os.path.dirname(OUT), NAME + ext))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build the sparse dedicated melee recording room.")
    parser.add_argument("--compile", action="store_true")
    parser.add_argument("--tools", default=TOOLS)
    parser.add_argument("--work", default=os.path.join(ROOT, "scratch", NAME + "_build"))
    args = parser.parse_args()
    write()
    if args.compile:
        compile_map(args.tools, args.work)
