int versionStatus(const char* folder)
{
    char path[MAX_OSPATH];
    q_snprintf(path, sizeof(path), "%s/pak2.pak", folder);
    int status = 3;
    const char* why = "it has no pak2.pak (patch 1): AD 1.80 or older";
    if(FILE* f = fopen(path, "rb"))
    {
        why = "its pak2.pak is not patch 1's";
        struct { char id[4]; int32_t offset; int32_t length; } header{};
        fseek(f, 0, SEEK_END);
        const long size = ftell(f);
        rewind(f);
        if(size == VR_AD_PAK2_SIZE && fread(&header, 1, sizeof(header), f) == sizeof(header) && !memcmp(header.id, "PACK", 4))
        {
            const int offset = LittleLong(header.offset), length = LittleLong(header.length);
            if(offset >= 12 && length > 0 && length < (1 << 20) && offset <= size - length)
            {
                za::Vector<unsigned char> bytes;
                bytes.resize(static_cast<za::SizeT>(length) + sizeof(header));
                memcpy(bytes.data(), &header, sizeof(header));
                if(!fseek(f, offset, SEEK_SET) && fread(bytes.data() + sizeof(header), 1, length, f) == size_t(length) &&
                    qvr::sha256::matches(qvr::sha256::of(bytes.data(), bytes.size()), VR_AD_PAK2_DIRSHA))
                {
                    status = 1;
                }
            }
        }
        fclose(f);
    }
    if(status != 1 && !versionWarned)
    {
        versionWarned = 1;
        Con_Printf("VR: Arcane Dimensions in %s is not the latest release (%s). Quake VR plays only AD 1.80 patch 1 "
                   "(\"1.81\", ad_v1_80p1final.zip): install it over this one.\n", folder, why);
    }
    return status;
}

bool skipInFolder(const char* filename)
{
    if(!q_strcasecmp(filename, "quake.rc") || !q_strcasecmp(filename, "progs.dat") || !q_strcasecmp(filename, "csprogs.dat"))
    {
        return true;
    }
    int lo = 0, hi = int(countof(shadowedFiles)) - 1;
    while(lo <= hi)
    {
        const int mid = (lo + hi) / 2;
        const int c = q_strcasecmp(filename, shadowedFiles[mid].name);
        if(c == 0)
        {
            const int owner = shadowedFiles[mid].owner;
            return owner == 0 || Cvar_VariableValue(owner == 1 ? "vr_hipnotic_available" : "vr_rogue_available") != 0.f;
        }
        if(c < 0) { hi = mid - 1; } else { lo = mid + 1; }
    }
    return false;
}

void beforeLoad()
{
    mapState.campaign = VR_ActiveCampaign() == campaignIndex;
    mapState.adSpawns = mapState.oursShared = 0;
    countSignals(sv.worldmodel ? sv.worldmodel->entities : "");
    const bool mounted = adFolderMounted();
    mapState.rules = mapState.campaign || (mapState.signals >= 2 && mounted);
    Cvar_SetROM("vr_ad_rules", mapState.rules ? "1" : "0");
    Cvar_SetROM("vr_ad_mounted", mounted ? "1" : "0");
    if(mapState.rules)
    {
        Con_DPrintf("VR: Arcane Dimensions rules on (%s; %d signals)\n", mapState.campaign ? "campaign" : "detected",
            mapState.signals);
    }
}

