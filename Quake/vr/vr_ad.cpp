// vr_ad.cpp -- Arcane Dimensions support, the engine's side (vr_ad.hpp; docs/vr-port/ARCANE_DIMENSIONS.md, 5 and 15).
//
// AD is campaign 6 ("ad", vr_gamedir.cpp). Its QuakeC is in Quake VR's progs, every name prefixed "ad_" (QC/ad/,
// Misc/quakevr/ad_import.py), and runs only in maps played by AD's rules (vr_ad_rules):
// - the release: only the latest, 1.80 patch 1 ("1.81"), is accepted; an older one is refused, said in the console;
// - AD's folder (mounted while AD is the campaign, above Quake's and the packs', under quakevr) supplies only its own
//   files: those an official pak has too are skipped there (vr_ad_data.inc, generated by ad_import.py), so AD's
//   menu art, weapon models and sounds never replace Quake's; AD's start.bsp is its hub and stays;
// - vr_ad_rules: the AD campaign, or (when AD's folder is mounted) a map whose entities carry 2 or more AD signals
//   (AD-only classnames, AD worldspawn keys), set before the map spawns;
// - which version of a classname spawns there (pr_edict.c, "AD support"): AD's (ad_<classname>) for AD's own entities
//   and AD's world logic; Quake VR's for the vanilla monsters, items and weapons, the player's spawn points, the
//   intermission and the level exit (decision 1; QC vr_ad_bridge.qc adapts AD's keys and flags on them);
// - a map key no field of Quake VR's has goes to AD's field of that name, ad_<key> (pr_edict.c ED_ParseEdict).

