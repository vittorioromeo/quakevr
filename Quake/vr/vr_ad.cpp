// The map now spawning (beforeLoad): whether AD's rules are on (its ruleset: vr_rules.cpp, which detects it and picks
// each classname's version), and AD's entities outside them.
struct MapState
{
    bool rules = false;
    bool mounted = false;
    bool outsideReady = false; // outside AD's rules: AD's reduced world setup done (QC VR_AD_WorldOnDemand)
    int outsideSpawns = 0;     // AD's entities spawned outside AD's rules (everywhereClasses)
} mapState;

int versionWarned = 0; // (said once per start)

template <za::SizeT N>
[[nodiscard]] bool listed(const char* const (&list)[N], const char* s)
{
    for(const char* e : list)
    {
        if(!ZA_STRCMP(e, s)) { return true; }
    }
    return false;
}

void statusCommand()
{
    Con_Printf("Arcane Dimensions: data %s (vr_ad_status %d); campaign %s\n",
        qvr::vr_ad_status.value == 1.f ? "1.80 patch 1, ready" :
        qvr::vr_ad_status.value == 3.f ? "another version: install ad_v1_80p1final.zip" :
        qvr::vr_ad_status.value == 2.f ? "incomplete/corrupt" : "missing",
        static_cast<int>(qvr::vr_ad_status.value), VR_ActiveCampaign() == qvr::ad::campaignIndex ? "active" : "not active");
    const int signals = qvr::rules::signals(qvr::rules::AD);
    Con_Printf("AD rules on this map: %s (%s; %d signals%s%s)\n", mapState.rules ? "on" : "off",
        mapState.rules && qvr::rules::byCampaign() ? "the AD campaign" : "detection", signals, signals ? ": " : "",
        qvr::rules::firstSignals(qvr::rules::AD));
    Con_Printf("AD spawns: %d entities with AD's function, %d shared classnames with Quake VR's, %d AD entities outside "
               "AD's rules\n", mapState.rules ? qvr::rules::importedSpawns() : 0, mapState.rules ? qvr::rules::oursShared() : 0,
        mapState.outsideSpawns);
}

